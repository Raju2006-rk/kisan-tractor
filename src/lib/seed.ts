function completedSession(
  bookingId: string,
  start: Date,
  end: Date,
  breakMinutes = 0,
) {
  const segments: WorkSegment[] =
    breakMinutes > 0
      ? [
          {
            start: iso(start),
            end: iso(new Date(start.getTime() + ((end.getTime() - start.getTime()) / 2))),
          },
          {
            start: iso(new Date(start.getTime() + ((end.getTime() - start.getTime()) / 2) + breakMinutes * 60000)),
            end: iso(end),
          },
        ]
      : [{ start: iso(start), end: iso(end) }];
  const totalMinutes = segments.reduce(
    (sum, segment) =>
      sum +
      Math.round(
        (new Date(segment.end!).getTime() - new Date(segment.start).getTime()) / 60000,
      ),
    0,
  );
  return {
    id: `ws_${bookingId}`,
    bookingId,
    segments,
    totalMinutes,
    createdAt: iso(start),
  };
}

