function makeHistory(
  bookingId: string,
  entries: {
    status: BookingStatus;
    actor: string;
    role: "farmer" | "owner" | "system";
    reason: string;
    at: string;
  }[],
): StatusHistory[] {
  return entries.map((entry, index) => ({
    id: `hist_${bookingId}_${index + 1}`,
    bookingId,
    oldStatus: index === 0 ? null : entries[index - 1].status,
    newStatus: entry.status,
    changedBy: entry.actor,
    changedByRole: entry.role,
    reason: entry.reason,
    createdAt: entry.at,
  }));
}

