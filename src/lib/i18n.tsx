const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({
  children,
  initialLanguage = "en",
}: {
  children: ReactNode;
  initialLanguage?: Language;
}) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);

  useEffect(() => {
    const stored = window.localStorage.getItem("kt_lang") as Language | null;
    if (
      stored &&
      LANGUAGES.some((item) => item.code === stored) &&
      stored !== language
    ) {
      // Sync the server-rendered language with the visitor's saved preference.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      setLanguageState(stored);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = RTL_LANGUAGES.includes(language) ? "rtl" : "ltr";
  }, [language]);

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    window.localStorage.setItem("kt_lang", next);
    window.localStorage.setItem("kt_lang_selected", "true");
    document.cookie = `kt_lang=${next}; path=/; max-age=31536000; samesite=lax`;
    document.cookie = `kt_lang_selected=1; path=/; max-age=31536000; samesite=lax`;
    fetch("/api/profile", {
      method: "PATCH",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ preferredLanguage: next }),
    }).catch(() => undefined);
  }, []);

  const t = useCallback(
    (key: Key, vars?: Record<string, string | number>) => {
      let value =
        dictionaries[language][key] ??
        dictionaries.en[key] ??
        (key as string);
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replaceAll(`{${name}}`, String(replacement));
        }
      }
      return value;
    },
    [language],
  );

  const value = useMemo<I18nValue>(() => {
    const locale = LANGUAGE_LOCALES[language] ?? "en-IN";
    return {
      language,
      setLanguage,
      t,
      locale,
      serviceLabel: (service) => {
        const key = `service.${service}` as Key;
        const translated = dictionaries[language][key];
        if (translated) return translated;
        const found = SERVICES.find((item) => item.id === service);
        return found?.name ?? service;
      },
      statusLabel: (status) =>
        dictionaries[language][`status.${status}` as Key] ??
        STATUS_META[status].label,
      roleLabel: (role) =>
        role === "farmer"
          ? t("common.farmer")
          : t("common.owner"),
      equipmentLabel: (id, fallback) => {
        const keys = EQUIPMENT_KEYS[id];
        return keys ? t(keys.label) : fallback;
      },
      equipmentDescription: (id, fallback) => {
        const keys = EQUIPMENT_KEYS[id];
        return keys ? t(keys.description) : fallback;
      },
    };
  }, [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside LanguageProvider");
  }
  return context;
}
